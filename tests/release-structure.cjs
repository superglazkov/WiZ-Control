// Cheap packaging regressions without requiring Electron or real hardware.
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const content = (name) => fs.readFileSync(path.join(root, name), 'utf8')
assert.equal(require('../package.json').version, '3.4.5')
assert.match(content('src/renderer/src/components/modals/HelpModal.tsx'), /window\.api\.getVersion\(\)/)
assert.doesNotMatch(content('src/renderer/src/components/modals/HelpModal.tsx'), /Version:\s*3\.0\.0/)
assert.doesNotMatch(content('src/renderer/src/components/modals/SettingsModal.tsx'), /Spanish|Auto-Detect|handleChangeLanguage/)
assert.doesNotMatch(content('src/i18n/index.ts'), /resources\/locales\/es/)
assert.match(content('src/renderer/src/main.tsx'), /import ['"]\.\.\/\.\.\/i18n['"]/, 'renderer must initialize i18n before rendering')
assert.equal(fs.existsSync(path.join(root, 'resources/locales/es/translation.json')), false)
assert.ok(fs.existsSync(path.join(root, 'resources/tray.png')))
assert.match(content('electron-builder.yml'), /extraResources:[\s\S]*resources\/tray\.png/)
assert.match(content('src/main/index.ts'), /title: 'WiZ Control'/)
assert.match(content('src/renderer/index.html'), /<title>WiZ Control<\/title>/)
assert.doesNotMatch(content('src/renderer/index.html'), /localhost:8097/)
assert.doesNotMatch(content('.gitignore'), /electron\.vite\.config\.\*/)
assert.doesNotMatch(content('resources/locales/en/translation.json'), /e\.g\. 192\.168\.1\.34/)
assert.match(content('src/renderer/src/components/modals/AddDeviceModal.tsx'), /IP address/)
assert.match(content('src/renderer/src/components/ui/BrightnessSlider.tsx'), /wiz-brightness-slider/)

assert.ok(fs.existsSync(path.join(root, 'src/renderer/src/theme.ts')), 'theme module must be packaged in source')
assert.match(content('src/renderer/src/main.tsx'), /applyTheme\(\)/, 'theme must be applied before rendering')
assert.match(content('src/renderer/src/components/modals/SettingsModal.tsx'), /setThemePreference\(next\)/, 'theme selector must update the preference')
assert.match(content('src/renderer/src/components/modals/SettingsModal.tsx'), /value=\{theme\}/, 'theme selector must reflect the saved preference')
assert.match(content('src/renderer/src/assets/main.css'), /html\[data-theme='light'\]/, 'light theme CSS must exist')
assert.match(require('../package.json').scripts['build:win'], /--publish never/, 'CI/local Windows build must not auto-publish through electron-builder')
assert.match(content('.github/workflows/release-windows.yml'), /softprops\/action-gh-release@v2/, 'GitHub Actions must publish the release asset')

